import pandas as pd
import numpy as np

# 1. Load Dataset from the correct path with proper encoding
file_name = '/DataCoSupplyChainDataset.csv'

try:
    df = pd.read_csv(file_name, encoding='ISO-8859-1')
except Exception as e:
    print(f"Error loading dataset: {e}")
    raise

print("Raw Dataset Loaded Successfully! Shape:", df.shape)

# 2. Extract Dim_Product
dim_product = df[['Product Card Id', 'Product Name', 'Category Id', 'Category Name', 'Product Price']].drop_duplicates()
dim_product.columns = ['ProductID', 'ProductName', 'CategoryID', 'CategoryName', 'UnitPrice']
np.random.seed(42)
dim_product['ReorderLevel'] = np.random.randint(15, 60, size=len(dim_product))

# 3. Extract Dim_Customer
dim_customer = df[['Customer Id', 'Customer Fname', 'Customer Lname', 'Customer City', 'Customer Segment']].drop_duplicates()
dim_customer['CustomerName'] = dim_customer['Customer Fname'].fillna('') + ' ' + dim_customer['Customer Lname'].fillna('')
dim_customer = dim_customer[['Customer Id', 'CustomerName', 'Customer City', 'Customer Segment']]
dim_customer.columns = ['CustomerID', 'CustomerName', 'City', 'Segment']

# 4. Extract Dim_Warehouse / Location
dim_warehouse = df[['Order Zipcode', 'Order Region', 'Order Country']].drop_duplicates().reset_index(drop=True)
dim_warehouse['WarehouseID'] = ['WH-' + str(i + 101) for i in dim_warehouse.index]
dim_warehouse.columns = ['ZipCode', 'Region', 'Country', 'WarehouseID']

# Merge WarehouseID back into main DataFrame using distinct left and right column mappings
df = df.merge(
    dim_warehouse,
    left_on=['Order Zipcode', 'Order Region', 'Order Country'],
    right_on=['ZipCode', 'Region', 'Country'],
    how='left'
)

# 5. Extract Fact_Sales
fact_sales = df[[
    'Order Item Id', 'order date (DateOrders)', 'shipping date (DateOrders)',
    'Customer Id', 'Product Card Id', 'WarehouseID',
    'Order Item Quantity', 'Sales', 'Delivery Status',
    'Days for shipping (real)', 'Days for shipment (scheduled)'
]].copy()

fact_sales.columns = [
    'OrderItemID', 'OrderDate', 'ShipDate',
    'CustomerID', 'ProductID', 'WarehouseID',
    'Quantity', 'SalesAmount', 'DeliveryStatus',
    'ActualShippingDays', 'ScheduledShippingDays'
]

# Standardize Dates
fact_sales['OrderDate'] = pd.to_datetime(fact_sales['OrderDate']).dt.date
fact_sales['ShipDate'] = pd.to_datetime(fact_sales['ShipDate']).dt.date

# 6. Export Cleaned Star Schema CSVs
dim_product.to_csv('Dim_Product.csv', index=False)
dim_customer.to_csv('Dim_Customer.csv', index=False)
dim_warehouse.to_csv('Dim_Warehouse.csv', index=False)
fact_sales.to_csv('Fact_Sales.csv', index=False)

print("\nSuccess! Generated 4 Star Schema CSV files:")
print("- Dim_Product.csv")
print("- Dim_Customer.csv")
print("- Dim_Warehouse.csv")
print("- Fact_Sales.csv")